// 사용자가 겪은 상황(검 9자루 전부 채집, 미네랄 174만)을 재현해 스크린샷을 남긴다.
import { createRequire } from 'node:module';
const { chromium } = createRequire(import.meta.url)('playwright');
const out = new URL('../shots/', import.meta.url).pathname;
const weapons = Array.from({ length: 30 }, (_, i) => ({ id: i + 1, type: 'sword', grade: 0, grade: i < 4 ? 0 : i % 7 === 0 ? 2 : i % 5 === 0 ? 1 : i === 9 ? 4 : 0, level: i < 4 ? 10 : i % 5 === 0 ? 6 : 3, type: ['sword', 'axe', 'staff', 'bow'][i % 4], pity: 0, traits: i < 4 ? ['atkPct', 'critChance'] : [], pendingTraits: null, loc: 'mine' }));
const save = { minerals: 1740000, weapons, nextId: 31, building: { tier: 0, hp: 5, hpLeft: 5, t: 0 }, bestDps: 0, bestDpsAt: 0, bestLevel: 10, maxStage: 0, lastSeen: Date.now(), meta: { coins: 0, rebirths: 0, unlocked: ['sword', 'axe', 'staff', 'bow'], perm: {}, discovered: [] } };
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 416, height: 900 }, deviceScaleFactor: 2 });
const errors = [];
page.on('pageerror', (e) => errors.push(e.message));
await page.addInitScript((data) => localStorage.setItem('enhance-save-v2', data), JSON.stringify(save));
await page.goto(process.argv[2]);
await page.click('#splash');
await page.waitForTimeout(1300);
const later = await page.$('#modal [data-act="close"]'); if (later) await later.click();
await page.waitForTimeout(400);
await page.evaluate(() => document.querySelector('.tiles').scrollIntoView());
await page.screenshot({ path: out + 'sc-tiles.png' });
await page.click('.guide');
await page.waitForTimeout(400);
await page.evaluate(() => window.scrollTo(0, 0));
await page.screenshot({ path: out + 'sc-after.png' });
await page.click('.tabs [data-tab="mine"]');
await page.waitForTimeout(400);
await page.waitForTimeout(700);
await page.screenshot({ path: out + 'sc-mine.png', fullPage: true });
await page.click('.tabs [data-tab="forge"]');
await page.waitForTimeout(300);
await page.screenshot({ path: out + 'sc-before-promote.png' });
await page.click('[data-act="promote-all"]');
await page.waitForTimeout(400);
await page.screenshot({ path: out + 'sc-combine.png' });
await page.click('.tabs [data-tab="boss"]');
await page.waitForTimeout(300);
await page.click('[data-act="challenge"]');
await page.waitForTimeout(900);
await page.screenshot({ path: out + 'sc-fight.png' });
console.log(JSON.stringify({ errors }));
await browser.close();
