// 두근 강화·심연 조각·출석·자랑 카드를 눌러 보고 스크린샷을 남긴다. 사용: node tools/features.mjs http://localhost:8123/
import { createRequire } from 'node:module';
const { chromium } = createRequire(import.meta.url)('playwright');
const out = new URL('../shots/', import.meta.url).pathname;
const weapons = Array.from({ length: 6 }, (_, i) => ({ id: i + 1, type: 'sword', grade: 2, level: 7, pity: 0, traits: ['critMult', 'critChance', 'atkPct', 'atkPct', 'critMult'], pendingTraits: null, loc: 'mine' }));
const save = { minerals: 9e8, weapons, nextId: 7, building: { tier: 6, hp: 5, hpLeft: 5, t: 0 }, bestDps: 0, bestDpsAt: 0, lastClearAt: 0, bestLevel: 7, maxStage: 4, lastSeen: Date.now(), meta: { coins: 12, rebirths: 2, unlocked: ['sword', 'axe'], perm: {}, discovered: [], shards: 40, protect: 0, daily: null } };
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2 });
const errors = [];
page.on('pageerror', (e) => errors.push(e.message));
await page.addInitScript((data) => { if (!sessionStorage.getItem('seeded')) { localStorage.setItem('enhance-save-v2', data); sessionStorage.setItem('seeded', '1'); } }, JSON.stringify(save));
await page.goto(process.argv[2]);
await page.click('#splash');
await page.waitForTimeout(1600);
await page.screenshot({ path: out + 'f-attend.png' });
await page.click('#modal [data-act="attend"]');
await page.waitForTimeout(300);
await page.screenshot({ path: out + 'f-forge.png', fullPage: true });
await page.click('[data-act="craft-protect"]');
await page.click('#view [data-act="enhance"]');
await page.waitForTimeout(450);
await page.screenshot({ path: out + 'f-suspense.png' });
await page.waitForTimeout(1200);
await page.screenshot({ path: out + 'f-result.png' });
await page.click('.tabs [data-tab="shop"]');
await page.waitForTimeout(400);
await page.screenshot({ path: out + 'f-shop.png' });
await page.click('.tabs [data-tab="forge"]');
await page.click('[data-act="brag"]');
await page.waitForTimeout(1500);
await page.screenshot({ path: out + 'f-brag.png' });
const card = await page.$eval('.brag img', (i) => i.src.length).catch(() => 0);
console.log(JSON.stringify({ errors, card }));
await browser.close();
